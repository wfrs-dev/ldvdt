// Command genlayout reads docs/layout.yaml and emits the fixed Go keyboard
// literal consumed by the domain package. It runs at build time (go:generate);
// the produced layout_gen.go is committed and the yaml is never read at runtime.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

type yamlKey struct {
	Top    string `yaml:"top"`
	Bottom string `yaml:"bottom"`
}

type yamlDoc struct {
	Keyboard struct {
		Rows map[string][]yamlKey `yaml:"rows"`
	} `yaml:"keyboard"`
}

var rowOrder = []string{"numeric", "upper", "middle", "bottom"}

func main() {
	yamlPath := flag.String("yaml", "docs/layout.yaml", "path to layout.yaml")
	outPath := flag.String("out", "internal/domain/layout_gen.go", "output Go file")
	flag.Parse()

	data, err := os.ReadFile(*yamlPath)
	if err != nil {
		fatal("read layout: %v", err)
	}

	var doc yamlDoc
	if err := yaml.Unmarshal(data, &doc); err != nil {
		fatal("parse layout: %v", err)
	}

	var b strings.Builder
	b.WriteString("// Code generated by genlayout from docs/layout.yaml; DO NOT EDIT.\n\n")
	b.WriteString("package domain\n\n")
	b.WriteString("// layoutKeyboard is the fixed ldvd keyboard layout, generated at build time.\n")
	b.WriteString("var layoutKeyboard = Keyboard{\n\tRows: []Row{\n")

	for _, name := range rowOrder {
		keys, ok := doc.Keyboard.Rows[name]
		if !ok {
			fatal("layout.yaml is missing row %q", name)
		}
		fmt.Fprintf(&b, "\t\t{Name: %q, Keys: []Key{\n", name)
		for i, k := range keys {
			fmt.Fprintf(&b, "\t\t\t{Row: %q, Index: %d, Top: %s, Bottom: %s},\n",
				name, i, runeLit(k.Top), runeLit(k.Bottom))
		}
		b.WriteString("\t\t}},\n")
	}

	b.WriteString("\t},\n}\n")

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fatal("mkdir: %v", err)
	}
	if err := os.WriteFile(*outPath, []byte(b.String()), 0o644); err != nil {
		fatal("write: %v", err)
	}
	fmt.Printf("genlayout: wrote %s (%d rows)\n", *outPath, len(rowOrder))
}

func runeLit(s string) string {
	if s == "" {
		return "0"
	}
	return fmt.Sprintf("%q", []rune(s)[0])
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genlayout: "+format+"\n", args...)
	os.Exit(1)
}
